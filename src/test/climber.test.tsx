import { act, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { BoulderGame } from '../components/BoulderGame'
import { BEST_KEY } from '../game/climber'

const advance = (ms: number) => act(() => { vi.advanceTimersByTime(ms) })
const start = () => fireEvent.click(screen.getByRole('button', { name: 'Losklettern' }))
const board = () => screen.getByRole('group', { name: /Chalk ’til you drop/ })
const key = (value: string, repeat = false) => fireEvent.keyDown(board(), { key: value, repeat })

beforeEach(() => { vi.useFakeTimers(); localStorage.clear() })
afterEach(() => { vi.useRealTimers(); localStorage.clear() })

describe('endless climber controls', () => {
  it('starts with Enter or Space and ignores key repeats after starting', () => {
    const view = render(<BoulderGame/>)
    key('Enter')
    expect(board()).toHaveFocus()
    expect(screen.queryByRole('button', { name: 'Losklettern' })).not.toBeInTheDocument()
    view.unmount()
    render(<BoulderGame/>)
    key(' ')
    key(' ', true)
    expect(screen.getByRole('button', { name: 'Spiel pausieren' })).toBeEnabled()
    expect(screen.queryByRole('button', { name: 'Weiterklettern' })).not.toBeInTheDocument()
  })
  it('renders the same adaptive timing boundaries used by the game', () => {
    const { container } = render(<BoulderGame/>)
    start()
    const zone = container.querySelector<HTMLElement>('.climb-perfect-zone')!
    const initialLeft = zone.style.left
    const initialWidth = parseFloat(zone.style.width)
    advance(1200); key('ArrowLeft')
    expect(parseFloat(zone.style.width)).toBeGreaterThan(initialWidth)
    expect(zone.style.left).not.toBe(initialLeft)
    const wider = parseFloat(zone.style.width)
    advance(350); key('ArrowRight')
    expect(parseFloat(zone.style.width)).toBeLessThan(wider)
  })
  it('waits to start, accepts arrow keys and ignores held keys', () => {
    render(<BoulderGame/>)
    advance(20000)
    expect(screen.getByRole('button', { name: 'Losklettern' })).toBeVisible()
    start()
    expect(board()).toHaveFocus()
    advance(1200); key('ArrowLeft', true)
    expect(screen.getByRole('status')).toHaveTextContent('Nächster Griff: links')
    key('ArrowLeft')
    expect(screen.getByRole('status')).toHaveTextContent('Nächster Griff: rechts')
    expect(screen.getByRole('status')).toHaveTextContent('Sauber')
    expect(localStorage.getItem(BEST_KEY)).toBe('2')
    advance(850); key('d')
    expect(localStorage.getItem(BEST_KEY)).toBe('4')
  })
  it('supports tapping both halves, loss and immediate restart', () => {
    render(<BoulderGame/>); start()
    expect(screen.getByRole('img', { name: '2 von 2 Leben' })).toBeVisible()
    advance(1200); fireEvent.click(screen.getByRole('button', { name: 'Links greifen' }))
    advance(850); fireEvent.click(screen.getByRole('button', { name: 'Rechts greifen' }))
    advance(400); fireEvent.click(screen.getByRole('button', { name: 'Rechts greifen' }))
    expect(screen.getByRole('status')).toHaveTextContent('Gerade noch')
    expect(screen.getByRole('img', { name: '1 von 2 Leben' })).toBeVisible()
    advance(500); fireEvent.click(screen.getByRole('button', { name: 'Rechts greifen' }))
    const restart = screen.getByRole('button', { name: 'Nochmal chalken' })
    expect(restart).toHaveFocus()
    expect(screen.getByRole('img', { name: '0 von 2 Leben' })).toBeVisible()
    expect(screen.getByRole('status')).toHaveTextContent('4,0 Meter')
    key('Enter')
    expect(screen.getByRole('img', { name: '2 von 2 Leben' })).toBeVisible()
    expect(board()).toHaveFocus()
    expect(screen.getByRole('status')).toHaveTextContent('Nächster Griff: links')
    expect(localStorage.getItem(BEST_KEY)).toBe('4')
  })
  it('pauses for manual pause, focus loss and hidden tabs; resumes only explicitly', () => {
    render(<BoulderGame/>); start(); advance(1000)
    fireEvent.click(screen.getByRole('button', { name: 'Spiel pausieren' }))
    advance(30000)
    expect(screen.getByRole('button', { name: 'Weiterklettern' })).toHaveFocus()
    fireEvent.click(screen.getByRole('button', { name: 'Weiterklettern' }))
    key('ArrowLeft')
    expect(screen.getByRole('status')).toHaveTextContent('Sauber')
    fireEvent(window, new Event('blur'))
    expect(screen.getByRole('button', { name: 'Weiterklettern' })).toBeVisible()
    fireEvent.click(screen.getByRole('button', { name: 'Weiterklettern' }))
    vi.spyOn(document, 'hidden', 'get').mockReturnValue(true)
    fireEvent(document, new Event('visibilitychange'))
    expect(screen.getByRole('status')).toHaveTextContent('pausiert')
  })
  it('pauses when tabbing away, supports P and does not consume modified keys', () => {
    render(<BoulderGame/>); start(); advance(1000)
    fireEvent.keyDown(board(), { key: 'ArrowLeft', ctrlKey: true })
    expect(screen.getByRole('status')).toHaveTextContent('Nächster Griff: links')
    key('p')
    expect(screen.getByRole('button', { name: 'Weiterklettern' })).toBeVisible()
    fireEvent.click(screen.getByRole('button', { name: 'Weiterklettern' }))
    key('Tab')
    expect(screen.getByRole('status')).toHaveTextContent('pausiert')
    expect(screen.getByRole('button', { name: 'Weiterklettern' })).toHaveFocus()
  })
  it('times out without input and cancels its animation loop when closed', () => {
    const cancel = vi.spyOn(window, 'cancelAnimationFrame')
    const { unmount } = render(<BoulderGame/>); start()
    advance(3300)
    expect(screen.getByRole('status')).toHaveTextContent('Gerade noch')
    advance(3300)
    expect(screen.getByRole('button', { name: 'Nochmal chalken' })).toBeVisible()
    fireEvent.click(screen.getByRole('button', { name: 'Nochmal chalken' }))
    unmount()
    expect(cancel).toHaveBeenCalled()
    advance(30000)
  })
})
