import { fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import App from '../App'
import { Dock } from '../components/Dock'
import { siteConfig } from '../content/site'

describe('canvas interactions', () => {
  it('shows all three products and hides unconfigured external dock actions', () => {
    render(<App/>)
    for (const name of ['shopvibes', 'showcase', 'Backlane']) expect(screen.getByRole('button', { name: `${name}: Details öffnen` })).toBeVisible()
    const dock = screen.getByRole('navigation', { name: 'Schnellnavigation' })
    expect(within(dock).getAllByRole('link')).toHaveLength(4)
    expect(within(dock).getByRole('link', { name: 'Arbeit' })).toHaveAttribute('href', '#work')
    expect(within(dock).getByRole('link', { name: /LinkedIn/ })).toHaveAttribute('href', 'https://www.linkedin.com/in/timsenhoffmann/')
    expect(within(dock).queryByRole('link', { name: /E-Mail/ })).not.toBeInTheDocument()
    expect(screen.getByRole('link', { name: /Mit mir auf Strava laufen/ })).toHaveAttribute('href', 'https://www.strava.com/athletes/137493657')
  })
  it('opens product windows by keyboard, switches products and returns focus after cancel', async () => {
    const user = userEvent.setup()
    render(<App/>)
    const trigger = screen.getByRole('button', { name: 'shopvibes: Details öffnen' })
    trigger.focus()
    await user.keyboard('{Enter}')
    const dialog = screen.getByRole('dialog')
    expect(dialog).toBeVisible()
    expect(screen.getByRole('button', { name: 'Fenster schließen' })).toHaveFocus()
    await user.click(within(dialog).getByRole('button', { name: 'showcase' }))
    expect(within(dialog).getByRole('heading', { name: 'Ein Produkt. Ein neuer Kontext.' })).toBeVisible()
    fireEvent(dialog, new Event('cancel', { cancelable: true }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(trigger).toHaveFocus()
    expect(document.body.style.overflow).toBe('')
  })
  it('opens and closes the remaining available details', async () => {
    render(<App/>)
    for (const label of ['GitHub und Experimente öffnen', 'Laufen: Details öffnen', 'Boulder-Minispiel starten']) {
      await userEvent.click(screen.getByRole('button', { name: label }))
      expect(screen.getByRole('dialog')).toBeVisible()
      await userEvent.click(screen.getByRole('button', { name: 'Fenster schließen' }))
      expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    }
  })
  it('opens the game ready for keyboard play without an expand control', async () => {
    const user = userEvent.setup()
    render(<App/>)
    const trigger = screen.getByRole('button', { name: 'Spielen: Chalk ’til you drop öffnen' })
    await user.click(trigger)
    const dialog = screen.getByRole('dialog', { name: 'Chalk ’til you drop' })
    expect(within(dialog).queryByRole('button', { name: 'Fenster vergrößern' })).not.toBeInTheDocument()
    expect(within(dialog).getByRole('button', { name: 'Losklettern' })).toHaveFocus()
    await user.keyboard(' ')
    expect(within(dialog).queryByRole('button', { name: 'Losklettern' })).not.toBeInTheDocument()
    expect(within(dialog).getByRole('group', { name: 'Chalk ’til you drop: Kletterwand' })).toHaveFocus()
    fireEvent(dialog, new Event('cancel', { cancelable: true }))
    expect(trigger).toHaveFocus()
  })
  it('opens the CV by keyboard and returns focus after cancel', async () => {
    const user = userEvent.setup()
    render(<App/>)
    const trigger = screen.getByRole('button', { name: 'Lebenslauf öffnen' })
    trigger.focus()
    await user.keyboard('{Enter}')
    const dialog = screen.getByRole('dialog', { name: 'Lebenslauf / Tim Hoffmann' })
    expect(within(dialog).getByRole('heading', { name: 'Tim Hoffmann.' })).toBeVisible()
    expect(within(dialog).getByRole('heading', { name: 'Co-Founder & CPO' })).toBeVisible()
    expect(within(dialog).getByRole('link', { name: /LinkedIn/ })).toHaveAttribute('href', 'https://www.linkedin.com/in/timsenhoffmann/')
    expect(screen.getByRole('button', { name: 'Fenster schließen' })).toHaveFocus()
    fireEvent(dialog, new Event('cancel', { cancelable: true }))
    expect(trigger).toHaveFocus()
    expect(document.body.style.overflow).toBe('')
  })
  it('reveals earlier CV roles and the complete qualifications without leaving the page', async () => {
    const user = userEvent.setup()
    render(<App/>)
    await user.click(screen.getByRole('button', { name: 'Lebenslauf öffnen' }))
    const role = screen.getByRole('heading', { name: 'Co-Founder & Product Lead @ lunary.ai', hidden: true })
    expect(role).not.toBeVisible()
    await user.click(screen.getByText('Frühere Stationen'))
    expect(role).toBeVisible()
    expect(screen.getByRole('heading', { name: 'Praktikum · Marketing' })).toBeVisible()
    await user.click(screen.getByText('Zertifikate & Weiterbildung'))
    expect(screen.getByRole('heading', { name: 'IBM AI Product Manager' })).toBeVisible()
    expect(screen.getByRole('heading', { name: 'Certificate of Membership' })).toBeVisible()
    await user.click(screen.getByRole('button', { name: 'Fenster schließen' }))
    expect(screen.getByRole('button', { name: 'Lebenslauf öffnen' })).toHaveFocus()
  })
  it('gives configured external actions valid and distinct destinations', () => {
    render(<Dock username="octocat" profile={{ ...siteConfig.profile, linkedinUrl: 'https://www.linkedin.com/in/example/', email: 'me@example.com' }} onPlay={() => {}}/>)
    expect(screen.getByRole('link', { name: /GitHub/ })).toHaveAttribute('href', 'https://github.com/octocat')
    expect(screen.getByRole('link', { name: /LinkedIn/ })).toHaveAttribute('target', '_blank')
    expect(screen.getByRole('link', { name: /E-Mail/ })).toHaveAttribute('href', 'mailto:me@example.com')
    expect(screen.getByRole('link', { name: /E-Mail/ })).not.toHaveAttribute('target')
  })
})
