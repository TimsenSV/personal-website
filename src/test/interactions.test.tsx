import { fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import App from '../App'
import { Dock } from '../components/Dock'
import { siteConfig } from '../content/site'

describe('canvas interactions', () => {
  it('opens Work as a project app, supports drilling in and returns to the dock', async () => {
    render(<App/>)
    const trigger = screen.getByRole('button', { name: 'Work' })
    await userEvent.click(trigger)
    const overview = screen.getByRole('dialog', { name: 'My work' })
    for (const name of ['shopvibes', 'showcase', 'backlane']) expect(within(overview).getByRole('button', { name: `${name}: open details` })).toBeVisible()
    await userEvent.click(within(overview).getByRole('button', { name: 'shopvibes: open details' }))
    expect(screen.getByRole('dialog', { name: 'My work / shopvibes' })).toBeVisible()
    await userEvent.click(screen.getByRole('button', { name: 'All projects' }))
    expect(screen.getByRole('dialog', { name: 'My work' })).toBeVisible()
    fireEvent(overview, new Event('cancel', { cancelable: true }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(trigger).toHaveFocus()
  })
  it('shows all three products and hides unconfigured external dock actions', () => {
    render(<App/>)
    for (const name of ['shopvibes', 'showcase', 'backlane']) expect(screen.getByRole('button', { name: `${name}: open details` })).toBeVisible()
    const dock = screen.getByRole('navigation', { name: 'Quick navigation' })
    expect(within(dock).getAllByRole('link')).toHaveLength(4)
    expect(within(dock).getByRole('link', { name: /Spotify/ })).toHaveAttribute('href', siteConfig.spotify.url)
    expect(within(dock).getByRole('link', { name: /Spotify/ })).toHaveAttribute('target', '_blank')
    expect(within(dock).getByRole('button', { name: 'Work' })).toBeVisible()
    expect(within(dock).getByRole('link', { name: /LinkedIn/ })).toHaveAttribute('href', 'https://www.linkedin.com/in/timsenhoffmann/')
    expect(within(dock).queryByRole('link', { name: /Email/ })).not.toBeInTheDocument()
    expect(screen.getByRole('link', { name: /Run with me on Strava/ })).toHaveAttribute('href', 'https://www.strava.com/athletes/137493657')
  })
  it('opens product windows by keyboard, switches products and returns focus after cancel', async () => {
    const user = userEvent.setup()
    render(<App/>)
    const trigger = screen.getByRole('button', { name: 'shopvibes: open details' })
    trigger.focus()
    await user.keyboard('{Enter}')
    const dialog = screen.getByRole('dialog')
    expect(dialog).toBeVisible()
    expect(screen.getByRole('button', { name: 'Close window' })).toHaveFocus()
    await user.click(within(dialog).getByRole('button', { name: 'showcase' }))
    expect(within(dialog).getByRole('heading', { name: 'Create lifestyle product images without a photoshoot.' })).toBeVisible()
    fireEvent(dialog, new Event('cancel', { cancelable: true }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(trigger).toHaveFocus()
    expect(document.body.style.overflow).toBe('')
  })
  it('opens and closes the remaining available details', async () => {
    render(<App/>)
    for (const label of ['Open GitHub and experiments', 'Running: open details', 'Start climbing game']) {
      await userEvent.click(screen.getByRole('button', { name: label }))
      expect(screen.getByRole('dialog')).toBeVisible()
      await userEvent.click(screen.getByRole('button', { name: 'Close window' }))
      expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    }
  })
  it('opens the game ready for keyboard play without an expand control', async () => {
    const user = userEvent.setup()
    render(<App/>)
    const trigger = screen.getByRole('button', { name: 'Play Grip Happens' })
    await user.click(trigger)
    const dialog = screen.getByRole('dialog', { name: 'Grip Happens' })
    expect(within(dialog).queryByRole('button', { name: 'Expand window' })).not.toBeInTheDocument()
    expect(within(dialog).getByRole('button', { name: 'Start climbing' })).toHaveFocus()
    await user.keyboard(' ')
    expect(within(dialog).queryByRole('button', { name: 'Start climbing' })).not.toBeInTheDocument()
    expect(within(dialog).getByRole('group', { name: 'Grip Happens: Climbing wall' })).toHaveFocus()
    fireEvent(dialog, new Event('cancel', { cancelable: true }))
    expect(trigger).toHaveFocus()
  })
  it('opens the CV by keyboard and returns focus after cancel', async () => {
    const user = userEvent.setup()
    render(<App/>)
    const trigger = screen.getByRole('button', { name: 'Open CV' })
    trigger.focus()
    await user.keyboard('{Enter}')
    const dialog = screen.getByRole('dialog', { name: 'CV / Tim Hoffmann' })
    expect(within(dialog).getByRole('heading', { name: 'Tim Hoffmann.' })).toBeVisible()
    expect(within(dialog).getByRole('heading', { name: 'Co-Founder & CPO' })).toBeVisible()
    expect(within(dialog).getByRole('link', { name: /LinkedIn/ })).toHaveAttribute('href', 'https://www.linkedin.com/in/timsenhoffmann/')
    expect(screen.getByRole('button', { name: 'Close window' })).toHaveFocus()
    fireEvent(dialog, new Event('cancel', { cancelable: true }))
    expect(trigger).toHaveFocus()
    expect(document.body.style.overflow).toBe('')
  })
  it('reveals earlier CV roles and the complete qualifications without leaving the page', async () => {
    const user = userEvent.setup()
    render(<App/>)
    await user.click(screen.getByRole('button', { name: 'Open CV' }))
    const role = screen.getByRole('heading', { name: 'Co-Founder & Product Lead @ lunary.ai', hidden: true })
    expect(role).not.toBeVisible()
    await user.click(screen.getByText('Previous roles'))
    expect(role).toBeVisible()
    expect(screen.getByRole('heading', { name: 'Marketing intern' })).toBeVisible()
    await user.click(screen.getByText('Certifications & learning'))
    expect(screen.getByRole('heading', { name: 'IBM AI Product Manager' })).toBeVisible()
    expect(screen.getByRole('heading', { name: 'Certificate of Membership' })).toBeVisible()
    await user.click(screen.getByRole('button', { name: 'Close window' }))
    expect(screen.getByRole('button', { name: 'Open CV' })).toHaveFocus()
  })
  it('gives configured external actions valid and distinct destinations', () => {
    render(<Dock username="octocat" profile={{ ...siteConfig.profile, linkedinUrl: 'https://www.linkedin.com/in/example/', email: 'me@example.com' }} onPlay={() => {}} onWork={() => {}}/>)
    expect(screen.getByRole('link', { name: /GitHub/ })).toHaveAttribute('href', 'https://github.com/octocat')
    expect(screen.getByRole('link', { name: /LinkedIn/ })).toHaveAttribute('target', '_blank')
    expect(screen.getByRole('link', { name: /Email/ })).toHaveAttribute('href', 'mailto:me@example.com')
    expect(screen.getByRole('link', { name: /Email/ })).not.toHaveAttribute('target')
    expect(screen.queryByRole('link', { name: /Spotify/ })).not.toBeInTheDocument()
  })
})
